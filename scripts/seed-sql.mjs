#!/usr/bin/env node
// Writes db/seed.sql from data/venues/*.json (upserts venues and their approved facts).
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const dir = path.join(root, 'data/venues');
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => (v === null || v === undefined ? 'null' : `${q(JSON.stringify(v))}::jsonb`);
const out = ['-- Generated by scripts/seed-sql.mjs. Safe to run again.', 'begin;'];
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json')).sort()) {
  const v = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  const a = v.address;
  out.push(`insert into venues (slug, wp_id, name, type, status, street, city, state, postal_code, country, lat, lng, region_state, region_state_name, region_city, region_city_name, phone, website, hours_tz, hours_ranges, listing_source, claimed, verification, photo, created_at, updated_at) values (${[
    q(v.slug), v.wp_id ?? 'null', q(v.name), q(v.type), q(v.status), q(a.street), q(a.city), q(a.state), q(a.postal_code), q(a.country),
    v.geo?.lat ?? 'null', v.geo?.lng ?? 'null', q(v.region.state), q(v.region.state_name), q(v.region.city), q(v.region.city_name),
    q(v.phone), q(v.website), q(v.hours?.tz ?? null), j(v.hours?.ranges ?? null), j(v.listing_source), v.claimed, q(v.verification), q(v.photo),
    q(v.created_at || null), q(v.updated_at || null),
  ].join(', ')}) on conflict (slug) do update set name = excluded.name, type = excluded.type, status = excluded.status, street = excluded.street, city = excluded.city, state = excluded.state, postal_code = excluded.postal_code, lat = excluded.lat, lng = excluded.lng, phone = excluded.phone, website = excluded.website, hours_tz = excluded.hours_tz, hours_ranges = excluded.hours_ranges, listing_source = excluded.listing_source, claimed = excluded.claimed, verification = excluded.verification, photo = excluded.photo, updated_at = excluded.updated_at;`);
  for (const x of v.facts) {
    out.push(`insert into facts (venue_slug, field, key, value, source_url, source_type, checked_at, confidence, flags, evidence_url, approved_at, approved_by) values (${[
      q(v.slug), q(x.field), q(x.key), j(x.value), q(x.source_url), q(x.source_type), q(x.checked_at || null), q(x.confidence),
      `array[${(x.flags || []).map(q).join(', ')}]::text[]`, q(x.evidence_url ?? null), q(x.approved_at || null), q(x.approved_by),
    ].join(', ')}) on conflict (venue_slug, key) do update set value = excluded.value, source_url = excluded.source_url, source_type = excluded.source_type, checked_at = excluded.checked_at, confidence = excluded.confidence, flags = excluded.flags, approved_at = excluded.approved_at, approved_by = excluded.approved_by;`);
  }
}
out.push('commit;', '');
fs.writeFileSync(path.join(root, 'db/seed.sql'), out.join('\n'));
console.log(`db/seed.sql written (${out.length - 3} statements).`);
