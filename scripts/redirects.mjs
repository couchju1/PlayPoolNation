#!/usr/bin/env node
/**
 * Writes dist/_redirects (Cloudflare Pages) after the build: every URL the old
 * WordPress site had goes to its closest page here with a 301, so links and
 * rankings carry over. Run by `npm run build`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { miles } from '../src/lib/open-status.js';

const root = process.cwd();
const dist = path.join(root, 'dist');
const venues = fs.readdirSync(path.join(root, 'data/venues')).filter((f) => f.endsWith('.json')).map((f) => JSON.parse(fs.readFileSync(path.join(root, 'data/venues', f), 'utf8')));
const metros = JSON.parse(fs.readFileSync(path.join(root, 'data/metros.json'), 'utf8'));
const exists = (url) => fs.existsSync(path.join(dist, url, 'index.html'));
const lines = ['# Generated by scripts/redirects.mjs. Old WordPress URLs to their new pages.'];
const add = (from, to) => lines.push(`${from} ${to} 301`);

// Old /listing/<slug>/ venue URLs (before 3 Oct 2026), from the import log.
const byId = new Map(venues.map((v) => [String(v.wp_id), v.slug]));
const csv = fs.readFileSync(path.join(root, 'docs/venues-imported.csv'), 'utf8').trim().split('\n').slice(1);
for (const row of csv) {
  const id = row.split(',')[0];
  const m = /playpoolnation\.com(\/listing\/[^/,]+\/)/.exec(row);
  if (m && byId.has(id)) add(m[1], `/place/${byId.get(id)}/`);
}

// City URLs that have no page here (one venue so far): the state page, or the metro page that covers them.
const seen = new Set();
for (const v of venues) {
  const url = `/places/${v.region.state}/${v.region.city}/`;
  if (seen.has(url) || !v.region.city) continue;
  seen.add(url);
  if (!exists(url)) {
    // Inside a metro that has its own page: send it there.
    const metro = v.geo && metros.find((m) => m.page && miles(m.lat, m.lng, v.geo.lat, v.geo.lng) <= m.radius_miles);
    add(url, metro ? `/places/${metro.slug}/` : `/places/${v.region.state}/`);
  }
}
// Metro main cities the old site sent to the metro page (Minneapolis, Detroit, Boston).
for (const m of metros.filter((x) => x.page)) {
  const [city, abbr] = m.location.split(', ');
  const state = venues.find((x) => x.address.state === abbr)?.region.state;
  const url = `/places/${state}/${city.toLowerCase().replace(/[^a-z0-9]+/g, '-')}/`;
  if (state && !seen.has(url) && !exists(url)) add(url, m.url ?? `/places/${m.slug}/`);
}

for (const [from, to] of [
  ['/find-pool-halls/', '/places/'],
  ['/add-your-hall/', '/add-a-venue/'],
  ['/claim-listing/', '/list-your-venue/'],
  ['/claim-your-listing/', '/list-your-venue/'],
  ['/promote/', '/list-your-venue/'],
  ['/advertise/', '/list-your-venue/'],
  ['/my-pool/', '/search/'],
  ['/events/', '/places/'],
  ['/tournaments/', '/places/'],
  ['/leagues/', '/places/'],
  ['/post-an-event/', '/places/'],
  ['/instructors/', '/places/'],
  ['/teach/', '/places/'],
  ['/sign-in/', '/'],
  ['/join/', '/'],
  ['/login-2/', '/'],
  ['/register-2/', '/'],
  ['/dashboard/', '/'],
  ['/home-2/', '/'],
  ['/blog/', '/'],
  ['/blog-2/', '/'],
  ['/blog-3/', '/'],
  ['/refund-policy/', '/terms-of-service/'],
  ['/feed/', '/'],
  ['/category/*', '/places/'],
  ['/region/*', '/places/'],
  ['/listing/*', '/places/'],
  ['/event/*', '/places/'],
  ['/league/*', '/places/'],
  ['/instructor/*', '/places/'],
  ['/my-account/*', '/'],
  ['/my-account-2/*', '/'],
  ['/cart/*', '/'],
  ['/cart-2/*', '/'],
  ['/checkout/*', '/'],
  ['/checkout-2/*', '/'],
  ['/shop/*', '/'],
  ['/shop-2/*', '/'],
  ['/places/washington-2/*', '/places/washington/:splat'],
]) add(from, to);

fs.writeFileSync(path.join(dist, '_redirects'), lines.join('\n') + '\n');
console.log(`dist/_redirects: ${lines.length - 1} rules.`);
