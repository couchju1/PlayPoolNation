#!/usr/bin/env node
/**
 * Writes dist/.htaccess for Hostinger (LiteSpeed/Apache) after the build:
 *  - every URL the old WordPress site had goes to its closest page here with a
 *    301, so links and rankings carry over
 *  - http and www go to https://playpoolnation.com
 *  - /api/event and /api/submit run the PHP scripts in /api/
 *  - 404 page, security headers and caching
 * Run by `npm run build`. scripts/check-build.mjs reads the "#R" lines.
 */
import fs from 'node:fs';
import path from 'node:path';
import { miles } from '../src/lib/open-status.js';

const root = process.cwd();
const dist = path.join(root, 'dist');
const venues = fs.readdirSync(path.join(root, 'data/venues')).filter((f) => f.endsWith('.json')).map((f) => JSON.parse(fs.readFileSync(path.join(root, 'data/venues', f), 'utf8')));
const metros = JSON.parse(fs.readFileSync(path.join(root, 'data/metros.json'), 'utf8'));
const exists = (url) => fs.existsSync(path.join(dist, url, 'index.html'));
const rules = [];
const add = (from, to) => rules.push([from, to]);

// Old /listing/<slug>/ venue URLs (before 3 Oct 2026), from the import log.
const byId = new Map(venues.map((v) => [String(v.wp_id), v.slug]));
const csv = fs.readFileSync(path.join(root, 'docs/venues-imported.csv'), 'utf8').trim().split('\n').slice(1);
for (const row of csv) {
  const id = row.split(',')[0];
  const m = /playpoolnation\.com(\/listing\/[^/,]+\/)/.exec(row);
  if (m && byId.has(id)) add(m[1], `/place/${byId.get(id)}/`);
}

// City URLs that have no page here (one venue so far): the state page, or the metro page that covers them.
const seen = new Set();
for (const v of venues) {
  const url = `/places/${v.region.state}/${v.region.city}/`;
  if (seen.has(url) || !v.region.city) continue;
  seen.add(url);
  if (!exists(url)) {
    // Inside a metro that has its own page: send it there.
    const metro = v.geo && metros.find((m) => m.page && miles(m.lat, m.lng, v.geo.lat, v.geo.lng) <= m.radius_miles);
    add(url, metro ? `/places/${metro.slug}/` : `/places/${v.region.state}/`);
  }
}
// Metro main cities the old site sent to the metro page (Minneapolis, Detroit, Boston).
for (const m of metros.filter((x) => x.page)) {
  const [city, abbr] = m.location.split(', ');
  const state = venues.find((x) => x.address.state === abbr)?.region.state;
  const url = `/places/${state}/${city.toLowerCase().replace(/[^a-z0-9]+/g, '-')}/`;
  if (state && !seen.has(url) && !exists(url)) add(url, m.url ?? `/places/${m.slug}/`);
}

for (const [from, to] of [
  ['/find-pool-halls/', '/places/'],
  ['/add-your-hall/', '/add-a-venue/'],
  ['/claim-listing/', '/list-your-venue/'],
  ['/claim-your-listing/', '/list-your-venue/'],
  ['/promote/', '/list-your-venue/'],
  ['/advertise/', '/list-your-venue/'],
  ['/my-pool/', '/search/'],
  ['/events/', '/places/'],
  ['/tournaments/', '/places/'],
  ['/leagues/', '/places/'],
  ['/post-an-event/', '/places/'],
  ['/instructors/', '/places/'],
  ['/teach/', '/places/'],
  ['/sign-in/', '/'],
  ['/join/', '/'],
  ['/login-2/', '/'],
  ['/register-2/', '/'],
  ['/dashboard/', '/'],
  ['/home-2/', '/'],
  ['/blog/', '/'],
  ['/blog-2/', '/'],
  ['/blog-3/', '/'],
  ['/refund-policy/', '/terms-of-service/'],
  ['/feed/', '/'],
  ['/category/*', '/places/'],
  ['/region/*', '/places/'],
  ['/listing/*', '/places/'],
  ['/event/*', '/places/'],
  ['/league/*', '/places/'],
  ['/instructor/*', '/places/'],
  ['/my-account/*', '/'],
  ['/my-account-2/*', '/'],
  ['/cart/*', '/'],
  ['/cart-2/*', '/'],
  ['/checkout/*', '/'],
  ['/checkout-2/*', '/'],
  ['/shop/*', '/'],
  ['/shop-2/*', '/'],
  ['/places/washington-2/*', '/places/washington/:splat'],
]) add(from, to);

const esc = (p) => p.replace(/^\//, '').replace(/[.+?^${}()|[\]\\]/g, '\\$&');
const rewrite = ([from, to]) => {
  if (from.endsWith('/*')) {
    const base = esc(from.slice(0, -1));
    return `RewriteRule ^${base}(.*)$ ${to.replace(':splat', '$1')} [R=301,L]`;
  }
  // Match with or without the trailing slash.
  return `RewriteRule ^${esc(from).replace(/\/$/, '')}/?$ ${to} [R=301,L]`;
};

const htaccess = `# Generated by scripts/redirects.mjs on each build. Don't edit on the server.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html
AddDefaultCharset utf-8

<IfModule mod_rewrite.c>
RewriteEngine On

# One address: https://playpoolnation.com (other hostnames, like a preview domain, are left alone).
RewriteCond %{HTTP_HOST} ^www\\.playpoolnation\\.com$ [NC]
RewriteRule ^ https://playpoolnation.com%{REQUEST_URI} [R=301,L]
RewriteCond %{HTTPS} !=on
RewriteCond %{HTTP:X-Forwarded-Proto} !=https
RewriteCond %{HTTP_HOST} ^playpoolnation\\.com$ [NC]
RewriteRule ^ https://playpoolnation.com%{REQUEST_URI} [R=301,L]

# Click counts and forms (PHP, writes to Supabase).
RewriteRule ^api/(event|submit)/?$ api/$1.php [L]

# Old WordPress URLs.
${rules.map((r) => `#R ${r[0]} ${r[1]}\n${rewrite(r)}`).join('\n')}
</IfModule>

<Files "lib.inc.php">
  Require all denied
</Files>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "geolocation=(self), camera=(), microphone=()"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains" "expr=%{HTTP_HOST} =~ /playpoolnation\\.com$/"
</IfModule>

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType text/html "access plus 0 seconds"
  ExpiresByType application/xml "access plus 1 hour"
  ExpiresByType application/json "access plus 1 hour"
  ExpiresByType image/jpeg "access plus 30 days"
  ExpiresByType image/webp "access plus 30 days"
  ExpiresByType image/png "access plus 30 days"
  ExpiresByType image/svg+xml "access plus 30 days"
</IfModule>
`;
fs.writeFileSync(path.join(dist, '.htaccess'), htaccess);

// Hashed build files never change: cache them for a year.
fs.writeFileSync(path.join(dist, '_astro', '.htaccess'), '<IfModule mod_headers.c>\n  Header set Cache-Control "public, max-age=31536000, immutable"\n</IfModule>\n');
// The game's own pages aren't ours to have indexed.
fs.writeFileSync(path.join(dist, 'practice-game', '.htaccess'), '<IfModule mod_headers.c>\n  Header set X-Robots-Tag "noindex"\n  Header set Cache-Control "public, max-age=604800"\n</IfModule>\n');
console.log(`dist/.htaccess: ${rules.length} redirects.`);
